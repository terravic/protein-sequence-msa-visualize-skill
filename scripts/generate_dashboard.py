def compute_input_sequence_profiles(
    sequences: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """Compute raw unaligned input sequence statistics and biochemical composition."""
    hydrophobic_set = frozenset("AVLIMFWY")
    polar_set = frozenset("STNQ")
    acidic_set = frozenset("DE")
    basic_set = frozenset("KRH")
    special_set = frozenset("CGP")

    profiles: List[Dict[str, Any]] = []
    for seq_obj in sequences:
        aligned_seq = str(seq_obj.get("aligned_sequence", "")).upper()
        raw_seq = "".join(ch for ch in aligned_seq if ch not in ("-", "."))
        total = max(1, len(raw_seq))

        hydro = sum(1 for ch in raw_seq if ch in hydrophobic_set)
        polar = sum(1 for ch in raw_seq if ch in polar_set)
        acidic = sum(1 for ch in raw_seq if ch in acidic_set)
        basic = sum(1 for ch in raw_seq if ch in basic_set)
        special = sum(1 for ch in raw_seq if ch in special_set)

        kd_sum = sum(KYTE_DOOLITTLE_SCORES.get(ch, 0.0) for ch in raw_seq)
        gravy = round(kd_sum / total, 3)

        profiles.append(
            {
                "id": seq_obj["id"],
                "short_name": str(seq_obj["id"]).split("|")[-1],
                "description": seq_obj.get("description", seq_obj["id"]),
                "unaligned_length": len(raw_seq),
                "aligned_length": len(aligned_seq),
                "inserted_gaps": int(seq_obj.get("gap_count", len(aligned_seq) - len(raw_seq))),
                "gravy_hydropathy": gravy,
                "composition_pct": {
                    "hydrophobic": round(100.0 * hydro / total, 1),
                    "polar": round(100.0 * polar / total, 1),
                    "acidic": round(100.0 * acidic / total, 1),
                    "basic": round(100.0 * basic / total, 1),
                    "special": round(100.0 * special / total, 1),
                },
            }
        )
    return profiles


def render_initial_3d_network_svg(
    sequences: List[Dict[str, Any]],
    identity_matrices: Dict[str, Any],
    width: int = 680,
    height: int = 390,
) -> str:
    """Pre-render the initial 3D homology network SVG frame for instant display."""
    n = len(sequences)
    if n == 0:
        return ""
    node_colors = [
        "#38BDF8",
        "#10B981",
        "#F59E0B",
        "#EC4899",
        "#A855F7",
        "#14B8A6",
        "#F97316",
    ]
    nodes: List[Dict[str, Any]] = []
    for i, seq in enumerate(sequences):
        angle = (2.0 * math.pi * i) / max(1, n)
        radius = 110.0
        nodes.append(
            {
                "index": i,
                "id": str(seq["id"]),
                "label": str(seq["id"]).split("|")[-1],
                "length": int(seq.get("unaligned_length", 0)),
                "x": math.cos(angle) * radius,
                "y": (1.0 if i % 2 == 0 else -1.0) * 40.0 + (i - (n - 1) / 2.0) * 18.0,
                "z": math.sin(angle) * radius,
                "vx": 0.0,
                "vy": 0.0,
                "vz": 0.0,
                "color": node_colors[i % len(node_colors)],
            }
        )

    mat = identity_matrices.get("coverage") or identity_matrices.get("global") or []
    for _ in range(60):
        for i in range(n):
            for j in range(i + 1, n):
                dx = nodes[j]["x"] - nodes[i]["x"]
                dy = nodes[j]["y"] - nodes[i]["y"]
                dz = nodes[j]["z"] - nodes[i]["z"]
                dist_sq = dx * dx + dy * dy + dz * dz + 10.0
                dist = math.sqrt(dist_sq)
                f_rep = 4200.0 / dist_sq
                rx = (dx / dist) * f_rep
                ry = (dy / dist) * f_rep
                rz = (dz / dist) * f_rep
                nodes[i]["vx"] -= rx
                nodes[i]["vy"] -= ry
                nodes[i]["vz"] -= rz
                nodes[j]["vx"] += rx
                nodes[j]["vy"] += ry
                nodes[j]["vz"] += rz

                ident = (
                    float(mat[i][j])
                    if i < len(mat) and j < len(mat[i])
                    else 20.0
                )
                target_dist = max(55.0, 210.0 - ident * 1.45)
                diff = dist - target_dist
                f_attr = 0.018 * diff
                ax = (dx / dist) * f_attr
                ay = (dy / dist) * f_attr
                az = (dz / dist) * f_attr
                nodes[i]["vx"] += ax
                nodes[i]["vy"] += ay
                nodes[i]["vz"] += az
                nodes[j]["vx"] -= ax
                nodes[j]["vy"] -= ay
                nodes[j]["vz"] -= az

        for i in range(n):
            nodes[i]["vx"] = (nodes[i]["vx"] - nodes[i]["x"] * 0.008) * 0.82
            nodes[i]["vy"] = (nodes[i]["vy"] - nodes[i]["y"] * 0.008) * 0.82
            nodes[i]["vz"] = (nodes[i]["vz"] - nodes[i]["z"] * 0.008) * 0.82
            nodes[i]["x"] += nodes[i]["vx"]
            nodes[i]["y"] += nodes[i]["vy"]
            nodes[i]["z"] += nodes[i]["vz"]

    rot_x = 0.32
    rot_y = -0.45
    cos_y, sin_y = math.cos(rot_y), math.sin(rot_y)
    cos_x, sin_x = math.cos(rot_x), math.sin(rot_x)

    def project(x: float, y: float, z: float) -> Dict[str, float]:
        x1 = x * cos_y - z * sin_y
        z1 = z * cos_y + x * sin_y
        y2 = y * cos_x - z1 * sin_x
        z2 = z1 * cos_x + y * sin_x
        scale = 420.0 / max(80.0, 420.0 + z2)
        return {
            "sx": width / 2.0 + x1 * scale,
            "sy": height / 2.0 + y2 * scale,
            "z": z2,
            "scale": scale,
        }

    svg_parts: List[str] = [
        f'<ellipse cx="{width / 2.0:.1f}" cy="{height / 2.0 + 18:.1f}" rx="235" ry="78" fill="none" stroke="rgba(148, 163, 184, 0.16)" stroke-dasharray="4 4" stroke-width="1" />',
        f'<ellipse cx="{width / 2.0:.1f}" cy="{height / 2.0 + 18:.1f}" rx="145" ry="48" fill="none" stroke="rgba(148, 163, 184, 0.12)" stroke-dasharray="3 3" stroke-width="1" />',
    ]

    for nd in nodes:
        p = project(nd["x"], nd["y"], nd["z"])
        nd["sx"] = p["sx"]
        nd["sy"] = p["sy"]
        nd["depth"] = p["z"]
        nd["sr"] = max(8, round(13.0 * p["scale"]))

    for i in range(n):
        for j in range(i + 1, n):
            ident = float(mat[i][j]) if i < len(mat) and j < len(mat[i]) else 0.0
            if ident < 15.0:
                continue
            alpha = min(0.88, max(0.22, ident / 100.0))
            stroke_color = (
                f"rgba(16, 185, 129, {alpha:.2f})"
                if ident >= 35.0
                else f"rgba(56, 189, 248, {alpha:.2f})"
            )
            stroke_w = max(1.2, ident / 22.0)
            svg_parts.append(
                f'<line x1="{nodes[i]["sx"]:.1f}" y1="{nodes[i]["sy"]:.1f}" '
                f'x2="{nodes[j]["sx"]:.1f}" y2="{nodes[j]["sy"]:.1f}" '
                f'stroke="{stroke_color}" stroke-width="{stroke_w:.1f}" />'
            )
            mx = (nodes[i]["sx"] + nodes[j]["sx"]) / 2.0
            my = (nodes[i]["sy"] + nodes[j]["sy"]) / 2.0
            svg_parts.append(
                f'<text x="{mx + 4.0:.1f}" y="{my - 3.0:.1f}" '
                f'fill="rgba(203, 213, 225, 0.82)" font-size="10" font-family="monospace">'
                f"{ident:.1f}%</text>"
            )

    for nd in sorted(nodes, key=lambda item: item["depth"], reverse=True):
        label_esc = html.escape(nd["label"])
        svg_parts.append(
            f'<circle cx="{nd["sx"]:.1f}" cy="{nd["sy"]:.1f}" r="{nd["sr"]}" '
            f'fill="{nd["color"]}" stroke="#FFFFFF" stroke-width="1.5" />'
        )
        svg_parts.append(
            f'<text x="{nd["sx"] + nd["sr"] + 6.0:.1f}" y="{nd["sy"] + 4.0:.1f}" '
            f'fill="#F8FAFC" font-size="12" font-family="monospace">'
            f'{label_esc} ({nd["length"]}aa)</text>'
        )

    return "\n".join(svg_parts)


