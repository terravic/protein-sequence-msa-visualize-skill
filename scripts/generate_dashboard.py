def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Compile standalone interactive HTML5 dashboard (dashboard.html) from MSA artifacts."
    )
    parser.add_argument(
        "--alignment",
        type=Path,
        required=True,
        help="Path to aligned FASTA file.",
    )
    parser.add_argument(
        "--metrics",
        type=Path,
        required=True,
        help="Path to computed metrics JSON from analyze_msa.py.",
    )
    parser.add_argument(
        "--pim",
        type=Path,
        default=None,
        help="Optional path to Percent Identity Matrix file or JSON.",
    )
    parser.add_argument(
        "--tree",
        type=Path,
        default=None,
        help="Optional path to Newick guide tree file.",
    )
    parser.add_argument(
        "--title",
        type=str,
        default="Multiple Sequence Alignment Analysis",
        help="Custom dashboard title.",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        required=True,
        help="Output HTML path (e.g., dashboard.html).",
    )
    return parser


def main(argv: Optional[List[str]] = None) -> int:
    parser = build_arg_parser()
    args = parser.parse_args(argv)
    try:
        compile_dashboard(
            alignment_path=args.alignment,
            metrics_path=args.metrics,
            output_html_path=args.output,
            pim_path=args.pim,
            tree_path=args.tree,
            title=args.title,
        )
        return 0
    except FileNotFoundError as exc:
        logger.error("%s", exc)
        return 1
    except Exception as exc:  # pragma: no cover
        logger.error("Unexpected error in generate_dashboard: %s", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
